import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDir, '..');
const defaultOutDir = resolve(projectRoot, 'src/features/watchlists/generated');

const expectedSourceIds = [
  'nse-sectors',
  'nse-indices',
  'bse-sectors',
  'bse-indices',
  'nse-all-stocks-sectors',
  'bse-all-stocks-sectors',
];

const splitDefinitions = [
  ['nse-sectors', 'officialWatchlistNseSectors.generated.ts', 'officialWatchlistNseSectorsSourceSnapshot'],
  ['nse-indices', 'officialWatchlistNseIndices.generated.ts', 'officialWatchlistNseIndicesSourceSnapshot'],
  ['bse-sectors', 'officialWatchlistBseSectors.generated.ts', 'officialWatchlistBseSectorsSourceSnapshot'],
  ['bse-indices', 'officialWatchlistBseIndices.generated.ts', 'officialWatchlistBseIndicesSourceSnapshot'],
];

function parseArgs(argv) {
  let check = false;
  let outDir = defaultOutDir;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      check = true;
      continue;
    }
    if (arg === '--out-dir') {
      const value = argv[index + 1];
      if (!value) throw new Error('--out-dir requires a path.');
      outDir = resolve(value);
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${arg}`);
  }
  if (check && outDir !== defaultOutDir) {
    throw new Error('--check cannot be combined with --out-dir.');
  }
  return { check, outDir };
}

function parseGeneratedSnapshotText(text, filePath) {
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start < 0 || end < start) {
    throw new Error(`Could not find snapshot object in ${filePath}`);
  }
  const parsed = JSON.parse(text.slice(start, end + 1));
  if (!parsed || !Array.isArray(parsed.sources)) {
    throw new Error(`Snapshot ${filePath} must contain a sources array.`);
  }
  for (const source of parsed.sources) validateSource(source, filePath);
  return parsed;
}

function validateSource(source, filePath) {
  for (const field of ['id', 'label', 'watchlistPrefix', 'exchange']) {
    if (typeof source?.[field] !== 'string' || !source[field].trim()) {
      throw new Error(`Snapshot ${filePath} source is missing ${field}.`);
    }
  }
  if (!Array.isArray(source.groups)) {
    throw new Error(`Snapshot ${filePath} source ${source.id} is missing groups.`);
  }
  for (const group of source.groups) {
    for (const field of ['id', 'name', 'exchange', 'officialSourceUrl']) {
      if (typeof group?.[field] !== 'string' || !group[field].trim()) {
        throw new Error(`Snapshot ${filePath} source ${source.id} group is missing ${field}.`);
      }
    }
    if (!Array.isArray(group.members)) {
      throw new Error(`Snapshot ${filePath} source ${source.id} group ${group.id} is missing members.`);
    }
  }
}

function readSnapshot(relativePath) {
  const path = resolve(projectRoot, relativePath);
  return parseGeneratedSnapshotText(readFileSync(path, 'utf8'), path);
}

function requireSingleSource(sources, sourceId) {
  const matches = sources.filter((source) => source.id === sourceId);
  if (matches.length !== 1) {
    throw new Error(`Expected exactly one ${sourceId} source; found ${matches.length}.`);
  }
  return matches[0];
}

function stableModule(exportName, value) {
  return `// Generated by scripts/split-official-watchlist-data.mjs. Do not edit by hand.\nexport const ${exportName} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function buildCatalog(sources) {
  return {
    sources: sources.map((source) => {
      const meta = {
        id: source.id,
        label: source.label,
        watchlistPrefix: source.watchlistPrefix,
        exchange: source.exchange,
      };
      if (source.refreshMode !== undefined) meta.refreshMode = source.refreshMode;
      meta.groups = source.groups.map((group) => ({
        id: group.id,
        name: group.name,
        exchange: group.exchange,
        officialSourceUrl: group.officialSourceUrl,
        memberCount: group.members.length,
      }));
      return meta;
    }),
  };
}

function buildOutputs() {
  const official = readSnapshot('src/features/watchlists/officialWatchlistData.generated.ts').sources;
  const nseAll = readSnapshot('src/features/watchlists/nseSectorUniverseWatchlistData.generated.ts').sources;
  const bseAll = readSnapshot('src/features/watchlists/bseSectorUniverseWatchlistData.generated.ts').sources;
  const allSources = [...official, ...nseAll, ...bseAll];
  const actualIds = allSources.map((source) => source.id);
  if (JSON.stringify(actualIds) !== JSON.stringify(expectedSourceIds)) {
    throw new Error(`Expected canonical source IDs ${expectedSourceIds.join(', ')}; received ${actualIds.join(', ')}.`);
  }

  const outputs = new Map();
  for (const [sourceId, fileName, exportName] of splitDefinitions) {
    const source = requireSingleSource(allSources, sourceId);
    outputs.set(fileName, stableModule(exportName, { sources: [source] }));
  }
  outputs.set(
    'officialWatchlistCatalog.generated.ts',
    stableModule('officialWatchlistCatalogSnapshot', buildCatalog(allSources)),
  );
  return outputs;
}

function main() {
  const { check, outDir } = parseArgs(process.argv.slice(2));
  const outputs = buildOutputs();
  if (check) {
    const mismatches = [];
    for (const [fileName, content] of outputs) {
      const path = resolve(defaultOutDir, fileName);
      if (!existsSync(path) || readFileSync(path, 'utf8') !== content) mismatches.push(fileName);
    }
    if (mismatches.length) {
      console.error(`[FAIL] W1.3 generated outputs differ: ${mismatches.join(', ')}`);
      process.exitCode = 1;
      return;
    }
    console.log(`[PASS] W1.3 generated outputs are deterministic and current (${outputs.size} artifacts).`);
    return;
  }

  mkdirSync(outDir, { recursive: true });
  for (const [fileName, content] of outputs) {
    writeFileSync(resolve(outDir, fileName), content, 'utf8');
  }
  console.log(`[PASS] W1.3 generated ${outputs.size} artifacts in ${outDir}`);
}

main();
